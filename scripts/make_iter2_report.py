"""Generate docs/07_iter2_zero_gpu_results.md from results/<run>/iter2_matrix.json. Every number is read from the JSON.

  python scripts/make_iter2_report.py --out q35_0p8b
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.common import ROOT

ORDER = ["never", "best_global", "ent_thr_prefill", "conf_thr",
         "two_S0_u", "two_S0_t", "two_S1_u", "two_S1_t", "two_S2_u", "two_S2_t", "two_S4_u", "two_S4_t",
         "dlt_S0_u", "dlt_S0_t", "dlt_S1_u", "dlt_S1_t", "dlt_S2_u", "dlt_S2_t", "dlt_S4_u", "dlt_S4_t",
         "pc_S0", "pc_S1", "pc_S2", "pc_S4",
         "two_S1p_u", "two_S1p_t", "two_S0+S4_u", "two_S0+S4_t", "two_S1+S4_u", "two_S1+S4_t"]
NAMES = {"never": "never call", "best_global": "best fixed pattern (per lambda, cal)", "ent_thr_prefill": "prefill-entropy threshold (tuned)",
         "conf_thr": "answer-confidence threshold (Anchor-lite)"}
FAM = {"S0": "S0 surface", "S1": "S1 hidden", "S2": "S2 prefill entropy", "S4": "S4 draft confidence", "S1p": "S1' distilled student",
       "S0+S4": "S0 + S4 fused", "S1+S4": "S1 + S4 fused"}
EST = {"two": "two-head", "dlt": "single-head delta", "pc": "policy-consistent"}


def nm(c):
    if c in NAMES:
        return NAMES[c]
    e, rest = c.split("_", 1)
    fam, _, tun = rest.rpartition("_") if rest.endswith(("_u", "_t")) else (rest, "", "")
    return f"{EST[e]} on {FAM[fam]}" + (" (tuned)" if tun == "t" else " (untuned)" if tun == "u" else "")


def f(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


def ci(c):
    return f"{c['diff']:+.2f} [{c['ci_lo']:+.2f}, {c['ci_hi']:+.2f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    J = json.loads((ROOT / "results" / args.out / "iter2_matrix.json").read_text())
    P = [J[k] for k in ("partition_0", "partition_1", "partition_2")]
    L = [f"# 07 - Iteration 2, zero-GPU matrix on {args.out} (generated)", "",
         f"**Generated by `scripts/make_iter2_report.py` from `results/{args.out}/iter2_matrix.json`. Do not edit by hand.** {J['label']}.",
         f"Bootstrap resamples: {J['bootstrap']}. Emission charge: {J['emission_tokens_per_call']} tokens per tool call (the scaffold charges none). "
         "Test split, U-AUC points; 'mean' is over the three re-partitions of the same pool (not independent replications). "
         "Best controllers per timing class are chosen on the GATE split only.", "",
         "## 1. All controllers", "", "| Controller | Needs draft | Test U-AUC p0 | p1 | p2 | mean | Tokens / instance (mean) |", "|---|---|---|---|---|---|---|"]
    for c in ORDER:
        if c not in P[0]["controllers"]:
            continue
        u = [p["controllers"][c]["test_u_auc"] for p in P]
        tk = np.mean([p["controllers"][c]["test_tokens_per_instance"] for p in P])
        L.append(f"| {nm(c)} | {'yes' if P[0]['controllers'][c]['needs_draft'] else 'no'} | {u[0]:.2f} | {u[1]:.2f} | {u[2]:.2f} | {np.mean(u):.2f} | {tk:.1f} |")
    L += ["", "## 2. Does the hidden state add anything beyond surface features? (same estimator, same tuning protocol)", "",
          "Difference in test U-AUC, S1 minus S0 (partition 0: diff [95% CI], Holm p guidance only; then diffs on partitions 1 and 2).", "",
          "| Contrast | Partition 0 | Holm p | Partition 1 diff | Partition 2 diff |", "|---|---|---|---|---|"]
    for fam in ("family_pregen_hidden_value", "family_postdraft_hidden_value"):
        for k in P[0][fam]:
            c0 = P[0][fam][k]
            L.append(f"| {k} | {ci(c0)} | {c0['p_holm_guidance_only']:.3f} | {P[1][fam][k]['diff']:+.2f} | {P[2][fam][k]['diff']:+.2f} |")
    L += ["", "## 3. Against the answer-confidence threshold (paired, test)", "", "| Controller | p0 diff [CI] | p1 diff | p2 diff |", "|---|---|---|---|"]
    for c in ORDER:
        if c in P[0]["vs_conf_thr"] and c not in ("never", "best_global"):
            L.append(f"| {nm(c)} | {ci(P[0]['vs_conf_thr'][c])} | {P[1]['vs_conf_thr'][c]['diff']:+.2f} | {P[2]['vs_conf_thr'][c]['diff']:+.2f} |")
    L += ["", "## 4. When to decide: best pre-generation vs best post-draft controller (chosen on the gate split)", "",
          "| Partition | Best pre-generation | Best post-draft | Test gap post - pre (U-AUC) | Token gap (per instance) | Break-even kappa* (points/token) | Paired contrast post - pre |", "|---|---|---|---|---|---|---|"]
    for i, p in enumerate(P):
        s = p["selection"]
        L.append(f"| {i} | {nm(s['best_pre_by_gate'])} | {nm(s['best_post_by_gate'])} | {s['test_u_auc_gap_post_minus_pre']:+.2f} | "
                 f"{s['test_token_gap_post_minus_pre']:+.1f} | {f(s['kappa_star_points_per_token'])} | {ci(s['contrast_post_minus_pre'])} |")
    L += ["", "## 5. Net U-AUC when draft tokens are charged (partition 0, kappa in points per generated token)", "",
          "| Controller | " + " | ".join(f"kappa={k}" for k in J["kappas_points_per_token"]) + " |", "|---|" + "---|" * len(J["kappas_points_per_token"])]
    sel = {P[0]["selection"]["best_pre_by_gate"], P[0]["selection"]["best_post_by_gate"], "conf_thr", "two_S1_u", "two_S0_t", "never"}
    for c in ORDER:
        if c in sel:
            L.append(f"| {nm(c)} | " + " | ".join(f"{P[0]['controllers'][c]['test_net_u_auc_by_kappa'][str(k)]:.2f}" for k in J["kappas_points_per_token"]) + " |")
    L += ["", "## 6. Integrity checks and fitted hyper-parameters", ""]
    for i, p in enumerate(P):
        L.append(f"- partition {i}: max |U-AUC difference| versus stored Iteration-1 per-instance arrays: "
                 + ", ".join(f"{k} {v:.2e}" for k, v in p["integrity_max_abs_diff_vs_stored"].items()) + f"; info: {json.dumps(p['info'])}")
    out = ROOT.parent / "docs" / f"07_iter2_{args.out}_results.md"
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)
    if args.out == "q35_0p8b":
        default_out = ROOT.parent / "docs" / "07_iter2_zero_gpu_results.md"
        default_out.write_text("\n".join(L) + "\n")
        print("wrote default", default_out)


if __name__ == "__main__":
    main()
